# Build references/functions.md for a skill from the help pages of the INSTALLED
# package (the project's renv library), so the reference matches the version the
# notebooks actually use. Rerun after the package is updated:
#
#   Rscript .claude/skills/tidysdm/scripts/make_function_reference.R tidysdm .claude/skills/tidysdm/references/functions.md
#
# (run from the repository root, so that renv activates and the project library is used)
# For each help topic it keeps the title, description, usage and arguments; the
# full page (details, value, examples) is available with ?function in R or in the
# package source (man/*.Rd).

args <- commandArgs(trailingOnly = TRUE)
pkg <- args[1]
out <- args[2]
stopifnot(!is.na(pkg), !is.na(out), requireNamespace(pkg, quietly = TRUE))

db <- tools::Rd_db(pkg)
# exported functions plus registered S3 methods (e.g. predict.repeat_ensemble),
# whose help pages hold the arguments that matter most
s3 <- getNamespaceInfo(pkg, "S3methods")
exports <- c(getNamespaceExports(pkg), if (nrow(s3)) paste(s3[, 1], s3[, 2], sep = "."))

# Plain-text rendering of one help topic, without underlined headings
rd_text <- function(rd) {
  tools::Rd2txt_options(underline_titles = FALSE, width = 90)
  con <- textConnection("txt", "w", local = TRUE)
  on.exit(close(con))
  tools::Rd2txt(rd, out = con, options = list(underline_titles = FALSE))
  txt
}

# Keep only the sections an agent needs to choose and call a function
keep_sections <- c("Description:", "Usage:", "Arguments:")
all_headers <- c("Description:", "Usage:", "Arguments:", "Details:", "Value:", "Note:",
                 "References:", "See Also:", "Examples:", "Author(s):", "Format:",
                 "Source:", "Methods (by class):", "Functions:", "Fields:")
compact_topic <- function(txt) {
  txt <- sub("\\s+$", "", txt)
  header_rows <- which(trimws(txt) %in% all_headers)
  title <- trimws(paste(txt[seq_len(max(1, header_rows[1] - 1))], collapse = " "))
  body <- character(0)
  for (i in seq_along(header_rows)) {
    h <- trimws(txt[header_rows[i]])
    if (!h %in% keep_sections) next
    end <- if (i < length(header_rows)) header_rows[i + 1] - 1 else length(txt)
    section <- txt[(header_rows[i] + 1):end]
    section <- section[nzchar(trimws(section)) | c(FALSE, head(nzchar(trimws(section)), -1))]
    body <- c(body, paste0("**", sub(":$", "", h), "**"), "```", section, "```")
  }
  list(title = title, body = body)
}

aliases_of <- function(rd) {
  tags <- vapply(rd, function(x) attr(x, "Rd_tag"), character(1))
  unlist(lapply(rd[tags == "\\alias"], as.character))
}

topics <- lapply(names(db), function(f) {
  rd <- db[[f]]
  al <- aliases_of(rd)
  list(file = f, aliases = al, exported = intersect(al, exports), text = rd_text(rd))
})
is_fun <- vapply(topics, function(t) length(t$exported) > 0, logical(1))
topics <- topics[is_fun][order(vapply(topics[is_fun], function(t) t$exported[1], ""))]

lines <- c(
  paste0("# ", pkg, " ", as.character(utils::packageVersion(pkg)), ": function reference"),
  "",
  paste0("Generated by `scripts/make_function_reference.R` from the installed help pages on ",
         format(Sys.Date()), ". Each entry gives title, description, usage and arguments; ",
         "for details, value and examples use `?function` or the package source `man/*.Rd`."),
  "",
  "## Contents",
  "",
  vapply(topics, function(t) {
    ct <- compact_topic(t$text)
    paste0("- `", paste(t$exported, collapse = "`, `"), "`: ", ct$title)
  }, character(1)),
  ""
)
for (t in topics) {
  ct <- compact_topic(t$text)
  lines <- c(lines, paste0("## ", paste(t$exported, collapse = ", ")), "",
             paste0("*", ct$title, "*"), "", ct$body, "")
}
writeLines(lines, out, useBytes = TRUE)
cat("wrote", out, ":", length(topics), "topics,", length(lines), "lines\n")
